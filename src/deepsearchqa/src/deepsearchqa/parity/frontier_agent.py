"""Harbor agent that runs FrontierAgent's ReAct single agent on DeepSearchQA tasks.

Used for the parity experiment (Option A in the adapter README): the same
FrontierAgent pipeline runs on both sides, through the same launcher
(``frontier_launcher.run_worker``: one fresh FrontierAgent container per
question).

Usage (from the adapters repo root)::

    export FRONTIER_AGENT_IMAGE=frontier-agent:<commit>
    export FRONTIER_AGENT_ENV_FILE=/path/to/FrontierAgent/.env
    PYTHONPATH=src/deepsearchqa/src harbor run -p datasets/deepsearchqa-parity \\
        -a deepsearchqa.parity.frontier_agent:DeepSearchQAFrontierAgent

What this wrapper adds on top of running FrontierAgent directly:

* **Same prompt as the original side.** The adapter's ``instruction.md`` ends
  with a footer that tells a containerised CLI agent to write
  ``/workspace/answer.txt``. FrontierAgent returns its answer directly, so the
  footer is stripped and the worker sends FrontierAgent's native
  ``# Task\\n\\n{question}\\n`` text, exactly as the original-side runner does.
* **Answer hand-off.** The final answer is written to ``/workspace/answer.txt``
  in the Harbor task container, so the adapter's verifier (``tests/grade.py``)
  grades it unchanged. The answer is passed through verbatim, including
  FrontierAgent's ``<ANSWER_NOT_FOUND>`` sentinel, which the original side also
  sends to its judge as-is.
* **Failures are exceptions, not scores.** If no trajectory was produced
  (worker crash, pipeline error before answering), ``run`` raises, so Harbor
  records an exception, matching how the original-side runner excludes such
  trials.
"""

from __future__ import annotations

from pathlib import Path

from harbor.agents.base import BaseAgent
from harbor.environments.base import BaseEnvironment
from harbor.models.agent.context import AgentContext

from deepsearchqa.parity import frontier_launcher

FOOTER_MARKER = "\n\n---\n\nResearch the question above"
ANSWER_PATH = "/workspace/answer.txt"
# The adapter's task.toml sets [agent].timeout_sec = 3600; Harbor cancels the
# run at that point and the launcher kills the container. This inner limit is
# only a backstop.
WORKER_TIMEOUT_SEC = 3700


def extract_question(instruction: str) -> str:
    """Return the DeepSearchQA prompt without the adapter's answer-file footer."""
    question, sep, _ = instruction.rpartition(FOOTER_MARKER)
    if not sep:
        raise ValueError(
            "instruction.md footer not found; was the task generated by this adapter?"
        )
    return question.strip()


class DeepSearchQAFrontierAgent(BaseAgent):
    @staticmethod
    def name() -> str:
        return "deepsearchqa-frontier-agent"

    def version(self) -> str | None:
        try:
            image, _ = frontier_launcher.config()
        except RuntimeError:
            return None
        return image

    async def setup(self, environment: BaseEnvironment) -> None:
        frontier_launcher.config()  # fail fast before any trial work

    async def run(
        self,
        instruction: str,
        environment: BaseEnvironment,
        context: AgentContext,
    ) -> None:
        logs_dir = Path(self.logs_dir)
        result = await frontier_launcher.run_worker(
            extract_question(instruction), logs_dir, WORKER_TIMEOUT_SEC
        )
        context.metadata = {
            **(context.metadata or {}),
            "frontier_agent_image": self.version(),
            "predicted_answer": result.get("predicted"),
            "pipeline_error": result.get("error"),
            "duration_seconds": result.get("duration_seconds"),
            "openai_model": result.get("openai_model"),
        }

        exception = frontier_launcher.classify(result)
        if exception:
            raise RuntimeError(f"FrontierAgent produced no trajectory: {exception}")

        answer_file = logs_dir / "answer.txt"
        answer_file.write_text(result.get("predicted") or "", encoding="utf-8")
        await environment.upload_file(answer_file, ANSWER_PATH)
