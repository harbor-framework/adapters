"""Rescore retained parity runs under the adapter's current attribution rule.

Usage (from src/contextbench; `run_harness_parity.sh rescore` runs it):

    python -m parity.rescore --work-dir WORK_DIR --retained RETAINED_DIR

RETAINED_DIR is a finished parity work directory or the published bundle.
WORK_DIR must hold the prepared tasks, generated by the current adapter. No
model is called. For each retained run the script

1. replays every Harbor trial through Harbor with `parity.replay_agent`, so
   that Harbor's collect hook, artifact transfer and the generated task's
   verifier score the retained trajectory and patch;
2. extracts each Harbor trial's raw OpenHands log and each native ContextBench
   history with the vendored upstream OpenHands extractor, and scores the
   native history under the attribution rule after Harbor's OpenHands
   converter turns it into ATIF.

It writes under WORK_DIR/rescore the score records `original/run-NN/score.json`
(native history, upstream extractor) and `harbor/run-NN/score.json` (verifier
replay), which `report.py report --work-dir WORK_DIR/rescore` compares, and
`harness-extractor.json` and `.md`: the final metrics of each pairing of
harness and extractor.
"""

from __future__ import annotations

